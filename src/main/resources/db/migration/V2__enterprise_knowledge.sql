-- Phase 3: single-enterprise profile, enterprise knowledge metadata, persisted chunks,
-- and AI configuration extensions.

CREATE TABLE enterprise_profile (
    id VARCHAR(64) NOT NULL,
    name VARCHAR(200) NOT NULL,
    intro CHARACTER VARYING,
    industry VARCHAR(100),
    address VARCHAR(500),
    phone VARCHAR(50),
    website VARCHAR(200),
    business_hours VARCHAR(200),
    service_scope CHARACTER VARYING,
    wechat_corp_id VARCHAR(100),
    default_open_kfid VARCHAR(100),
    updated_at TIMESTAMP(6) NOT NULL
);
ALTER TABLE enterprise_profile ADD CONSTRAINT pk_enterprise_profile PRIMARY KEY (id);

ALTER TABLE knowledge_base ADD COLUMN enterprise_id VARCHAR(64) DEFAULT 'default' NOT NULL;
ALTER TABLE knowledge_base ADD COLUMN scope VARCHAR(20) DEFAULT 'PERSONAL' NOT NULL;
ALTER TABLE knowledge_base ADD COLUMN category VARCHAR(30);
ALTER TABLE knowledge_base ADD COLUMN title VARCHAR(500);
ALTER TABLE knowledge_base ADD COLUMN source_type VARCHAR(30);
ALTER TABLE knowledge_base ADD COLUMN status VARCHAR(20) DEFAULT 'READY' NOT NULL;
ALTER TABLE knowledge_base ADD COLUMN storage_path VARCHAR(1000);
ALTER TABLE knowledge_base ADD COLUMN mime_type VARCHAR(200);
ALTER TABLE knowledge_base ADD COLUMN file_size BIGINT;
ALTER TABLE knowledge_base ADD COLUMN error_message VARCHAR(2000);
ALTER TABLE knowledge_base ADD COLUMN metadata_json CHARACTER VARYING;
ALTER TABLE knowledge_base ADD COLUMN enabled BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE knowledge_base ADD COLUMN updated_at TIMESTAMP(6);
ALTER TABLE knowledge_base ALTER COLUMN external_user_id SET NULL;
CREATE INDEX idx_knowledge_scope ON knowledge_base (enterprise_id, scope, enabled);

CREATE TABLE knowledge_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    knowledge_id BIGINT NOT NULL,
    enterprise_id VARCHAR(64) DEFAULT 'default' NOT NULL,
    scope VARCHAR(20) NOT NULL,
    chunk_index INT NOT NULL,
    content CHARACTER VARYING NOT NULL,
    embedding BLOB,
    token_count INT,
    created_at TIMESTAMP(6) NOT NULL
);
ALTER TABLE knowledge_chunk ADD CONSTRAINT pk_knowledge_chunk PRIMARY KEY (id);
ALTER TABLE knowledge_chunk ADD CONSTRAINT uk_knowledge_chunk
    UNIQUE (knowledge_id, chunk_index);
ALTER TABLE knowledge_chunk ADD CONSTRAINT fk_knowledge_chunk_knowledge
    FOREIGN KEY (knowledge_id) REFERENCES knowledge_base (id) ON DELETE CASCADE;
CREATE INDEX idx_knowledge_chunk_scope ON knowledge_chunk (enterprise_id, scope, knowledge_id);

