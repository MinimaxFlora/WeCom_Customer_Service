-- Baseline schema of the upstream project (H2 2.3.x).
-- Existing installations are baselined at version 1; fresh installations run this file.

CREATE TABLE ai_config (
    external_user_id VARCHAR(255) NOT NULL,
    ai_api_key VARCHAR(255) NOT NULL,
    ai_base_url VARCHAR(255) NOT NULL,
    ai_model VARCHAR(255) NOT NULL,
    last_modified TIMESTAMP(6) NOT NULL,
    rag_api_key VARCHAR(255),
    rag_base_url VARCHAR(255),
    rag_enabled BOOLEAN NOT NULL,
    rag_model VARCHAR(255),
    sf_base_url VARCHAR(255) NOT NULL,
    sf_image_model VARCHAR(255) NOT NULL,
    sf_stt_model VARCHAR(255) NOT NULL,
    sf_tts_model VARCHAR(255) NOT NULL,
    sf_vlm_model VARCHAR(255) NOT NULL,
    sf_voice VARCHAR(255) NOT NULL,
    system_prompt CHARACTER VARYING NOT NULL
);
ALTER TABLE ai_config ADD CONSTRAINT pk_ai_config PRIMARY KEY (external_user_id);

CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    content CHARACTER VARYING NOT NULL,
    external_user_id VARCHAR(255) NOT NULL,
    message_type ENUM('FILE', 'IMAGE', 'TEXT') NOT NULL,
    meta CHARACTER VARYING,
    sender_type ENUM('ADMIN', 'USER') NOT NULL,
    timestamp TIMESTAMP(6) NOT NULL
);
ALTER TABLE chat_message ADD CONSTRAINT pk_chat_message PRIMARY KEY (id);

CREATE TABLE custom_reply (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    create_time TIMESTAMP(6),
    external_user_id VARCHAR(255),
    keyword VARCHAR(255) NOT NULL,
    match_type ENUM('CONTAINS', 'EQUALS') NOT NULL,
    reply VARCHAR(2048) NOT NULL
);
ALTER TABLE custom_reply ADD CONSTRAINT pk_custom_reply PRIMARY KEY (id);

CREATE TABLE keyword_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    external_user_id VARCHAR(255) NOT NULL,
    handler_name VARCHAR(255) NOT NULL,
    keywords CHARACTER VARYING NOT NULL,
    last_modified TIMESTAMP(6) NOT NULL
);
ALTER TABLE keyword_config ADD CONSTRAINT pk_keyword_config PRIMARY KEY (id);

CREATE TABLE knowledge_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    content CHARACTER VARYING NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    external_user_id VARCHAR(255) NOT NULL,
    file_name VARCHAR(255) NOT NULL
);
ALTER TABLE knowledge_base ADD CONSTRAINT pk_knowledge_base PRIMARY KEY (id);

CREATE TABLE manual_transfer_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    external_user_id VARCHAR(255) NOT NULL,
    last_message CHARACTER VARYING NOT NULL,
    request_time TIMESTAMP(6) NOT NULL,
    resolved BOOLEAN NOT NULL
);
ALTER TABLE manual_transfer_request ADD CONSTRAINT pk_manual_transfer_request PRIMARY KEY (id);

CREATE TABLE mcp_ai_config (
    external_user_id VARCHAR(255) NOT NULL,
    api_key VARCHAR(255) NOT NULL,
    base_url VARCHAR(255) NOT NULL,
    last_modified TIMESTAMP(6) NOT NULL,
    model VARCHAR(255) NOT NULL
);
ALTER TABLE mcp_ai_config ADD CONSTRAINT pk_mcp_ai_config PRIMARY KEY (external_user_id);

CREATE TABLE mcp_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255) NOT NULL,
    sse_endpoint VARCHAR(512) NOT NULL,
    type VARCHAR(50) NOT NULL,
    url VARCHAR(512) NOT NULL
);
ALTER TABLE mcp_config ADD CONSTRAINT pk_mcp_config PRIMARY KEY (id);

CREATE TABLE message_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    content CHARACTER VARYING,
    from_user VARCHAR(255),
    msg_id VARCHAR(255),
    msg_type VARCHAR(255),
    timestamp TIMESTAMP(6),
    to_user VARCHAR(255)
);
ALTER TABLE message_log ADD CONSTRAINT pk_message_log PRIMARY KEY (id);

CREATE TABLE user_mcp_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    external_user_id VARCHAR(255) NOT NULL,
    mcp_config_id BIGINT NOT NULL
);
ALTER TABLE user_mcp_permission ADD CONSTRAINT pk_user_mcp_permission PRIMARY KEY (id);

CREATE TABLE wechat_kf_account (
    open_kfid VARCHAR(255) NOT NULL,
    avatar VARCHAR(512) NOT NULL,
    name VARCHAR(255) NOT NULL
);
ALTER TABLE wechat_kf_account ADD CONSTRAINT pk_wechat_kf_account PRIMARY KEY (open_kfid);

CREATE TABLE we_chat_user (
    external_user_id VARCHAR(255) NOT NULL,
    avatar VARCHAR(512),
    blocked BOOLEAN NOT NULL,
    info CHARACTER VARYING,
    last_updated TIMESTAMP(6),
    nickname VARCHAR(255)
);
ALTER TABLE we_chat_user ADD CONSTRAINT pk_we_chat_user PRIMARY KEY (external_user_id);

ALTER TABLE message_log ADD CONSTRAINT uk_message_log_msg_id UNIQUE (msg_id);
ALTER TABLE mcp_config ADD CONSTRAINT uk_mcp_config_name UNIQUE (name);
ALTER TABLE user_mcp_permission ADD CONSTRAINT uk_user_mcp_permission UNIQUE (external_user_id, mcp_config_id);
ALTER TABLE manual_transfer_request ADD CONSTRAINT uk_manual_transfer_user UNIQUE (external_user_id);
ALTER TABLE user_mcp_permission ADD CONSTRAINT fk_user_mcp_config
    FOREIGN KEY (mcp_config_id) REFERENCES mcp_config (id);
ALTER TABLE manual_transfer_request ADD CONSTRAINT fk_manual_transfer_user
    FOREIGN KEY (external_user_id) REFERENCES we_chat_user (external_user_id);
